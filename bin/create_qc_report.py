#!/usr/bin/env python
"""Combine alignment and variant QC summaries into a unified project QC report.

Reads datavzrd YAML configs, sample metric TSVs, and sample QC flag TSVs
generated by summarise_align_qc.py and summarise_var_qc.py, then produces:
  1. <output_prefix>.project_qc_summary.tsv — PASS/WARN/FAIL counts and failure
     rate for alignment_qc, variants_qc, and total.
  2. <output_prefix>.qc_flags.tsv — merged per-sample QC flags keeping only
     flag columns raised in at least one sample, encoded as categorical
     PASS/WARN or PASS/FAIL strings, with N_warning_flags, N_fail_flags, and
     overall QC_status placed immediately after sample IDs.
  3. <output_prefix>.qc_flags_summary.tsv — per-flag PASS/FAIL sample counts
     across all configured QC flags for the datavzrd summary bar plot.
  4. <output_prefix>.project_qc_summary.js — custom HTML/CSS renderer used by
     datavzrd's render-html view for a clean, large-font project summary.
  5. <output_prefix>.datavzrd.yml — unified datavzrd configuration with
     project_qc_summary as default-view and sample-level tables linked by
     sample_id.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
from datetime import datetime

import polars as pl
import yaml

VERSION = 1.0
PRECISION = int(os.getenv("QC_REPORT_PRECISION", 5))
DEFAULT_MAX_ROWS_PER_PAGE = 50000


def log(msg: str = "", level: str = "INFO"):
    print(f"[{datetime.now().isoformat()}] - {level} - {msg}")


def read_flags_table(file_path: str, id_cols: list[str]) -> pl.DataFrame:
    """Read a QC flags TSV keeping sample ID columns as strings."""
    schema_overrides = {col: pl.String for col in id_cols}
    return pl.read_csv(file_path, separator='\t', schema_overrides=schema_overrides)


def summarize_status_row(section: str, status_series: pl.Series) -> dict:
    """Compute PASS/WARN/FAIL counts and failure rate for a status series."""
    n_samples = status_series.len()
    n_pass = int((status_series == 'PASS').sum())
    n_warn = int((status_series == 'WARN').sum())
    n_fail = int((status_series == 'FAIL').sum())
    failure_rate = round(n_fail / n_samples, PRECISION) if n_samples else None
    return {
        'section': section,
        'N_samples': n_samples,
        'N_PASS': n_pass,
        'N_WARN': n_warn,
        'N_FAIL': n_fail,
        'failure_rate': failure_rate,
    }


def _extract_section_flags(df: pl.DataFrame, prefix: str, secondary_id_col: str | None = None):
    """Rename flag and count columns with a section prefix to avoid collisions."""
    flag_cols = [c for c in df.columns if c.startswith(('WARN-', 'FAIL-'))]
    rename_map = {
        'N_WARN_conditions': f'__{prefix}_N_WARN',
        'N_FAIL_conditions': f'__{prefix}_N_FAIL',
    }
    warn_cols = []
    fail_cols = []
    for col in flag_cols:
        new_col = f'{prefix}-{col}'
        rename_map[col] = new_col
        if col.startswith('WARN-'):
            warn_cols.append(new_col)
        else:
            fail_cols.append(new_col)

    keep_cols = ['sample_id']
    if secondary_id_col and secondary_id_col in df.columns:
        keep_cols.append(secondary_id_col)
    keep_cols.extend(['N_WARN_conditions', 'N_FAIL_conditions'])
    keep_cols.extend(flag_cols)

    renamed = df.select(keep_cols).rename(rename_map)
    return renamed, warn_cols, fail_cols


def merge_qc_flags(align_flags_df: pl.DataFrame | None, var_flags_df: pl.DataFrame | None):
    """Merge align and var QC flag tables, recompute overall status, and drop all-zero flags.

    Active flag columns are encoded as categorical strings ('PASS'/'WARN' for
    warning flags and 'PASS'/'FAIL' for fail flags) so datavzrd automatic column
    bar plots treat them as categories rather than continuous numbers.
    """
    if align_flags_df is None and var_flags_df is None:
        raise ValueError('At least one of alignment or variant QC flags tables must be provided')

    warn_flag_cols = []
    fail_flag_cols = []
    id_cols = ['sample_id']

    if align_flags_df is not None:
        align_part, a_warn, a_fail = _extract_section_flags(align_flags_df, 'ALIGN', 'bam_sample_id')
        warn_flag_cols.extend(a_warn)
        fail_flag_cols.extend(a_fail)
        if 'bam_sample_id' in align_part.columns:
            id_cols.append('bam_sample_id')
    else:
        align_part = None

    if var_flags_df is not None:
        var_part, v_warn, v_fail = _extract_section_flags(var_flags_df, 'VAR', 'vcf_sample_id')
        warn_flag_cols.extend(v_warn)
        fail_flag_cols.extend(v_fail)
        if 'vcf_sample_id' in var_part.columns:
            id_cols.append('vcf_sample_id')
    else:
        var_part = None

    if align_part is not None and var_part is not None:
        merged = align_part.join(var_part, on='sample_id', how='full', coalesce=True)
        warn_expr = (
            pl.col('__ALIGN_N_WARN').fill_null(0).cast(pl.UInt32)
            + pl.col('__VAR_N_WARN').fill_null(0).cast(pl.UInt32)
        )
        fail_expr = (
            pl.col('__ALIGN_N_FAIL').fill_null(0).cast(pl.UInt32)
            + pl.col('__VAR_N_FAIL').fill_null(0).cast(pl.UInt32)
        )
    elif align_part is not None:
        merged = align_part
        warn_expr = pl.col('__ALIGN_N_WARN').fill_null(0).cast(pl.UInt32)
        fail_expr = pl.col('__ALIGN_N_FAIL').fill_null(0).cast(pl.UInt32)
    else:
        merged = var_part
        warn_expr = pl.col('__VAR_N_WARN').fill_null(0).cast(pl.UInt32)
        fail_expr = pl.col('__VAR_N_FAIL').fill_null(0).cast(pl.UInt32)

    merged = merged.with_columns(
        warn_expr.alias('N_warning_flags'),
        fail_expr.alias('N_fail_flags'),
    ).with_columns(
        pl.when(pl.col('N_fail_flags') > 0).then(pl.lit('FAIL'))
        .when(pl.col('N_warning_flags') > 0).then(pl.lit('WARN'))
        .otherwise(pl.lit('PASS')).alias('QC_status')
    )

    all_flag_cols = warn_flag_cols + fail_flag_cols
    active_flag_cols = [
        col for col in all_flag_cols
        if merged.height > 0 and bool((merged[col].fill_null(0) > 0).any())
    ]

    categorical_exprs = []
    for col in active_flag_cols:
        raised_label = 'WARN' if '-WARN-' in col else 'FAIL'
        categorical_exprs.append(
            pl.when(pl.col(col).is_null()).then(None)
            .when(pl.col(col) > 0).then(pl.lit(raised_label))
            .otherwise(pl.lit('PASS'))
            .alias(col)
        )
    if categorical_exprs:
        merged = merged.with_columns(categorical_exprs)

    output_cols = id_cols + ['N_warning_flags', 'N_fail_flags', 'QC_status'] + active_flag_cols
    return merged.select(output_cols), active_flag_cols


def build_qc_flags_summary(
    align_flags_df: pl.DataFrame | None,
    var_flags_df: pl.DataFrame | None,
) -> pl.DataFrame:
    """Build a tidy per-flag PASS/FAIL count table across all configured QC flags."""
    rows = []
    sections = [
        ('alignment_qc', 'ALIGN', align_flags_df),
        ('variants_qc', 'VAR', var_flags_df),
    ]
    for section, prefix, df in sections:
        if df is None:
            continue
        for col in df.columns:
            if not col.startswith(('WARN-', 'FAIL-')):
                continue
            severity = 'WARN' if col.startswith('WARN-') else 'FAIL'
            flag_label = f'{prefix}-{col}'
            n_raised = int((df[col] > 0).sum())
            n_pass = int((df[col] == 0).sum())
            rows.append({
                'flag': flag_label,
                'section': section,
                'severity': severity,
                'status': 'PASS',
                'count': n_pass,
            })
            rows.append({
                'flag': flag_label,
                'section': section,
                'severity': severity,
                'status': severity,
                'count': n_raised,
            })

    return pl.DataFrame(
        rows,
        schema={
            'flag': pl.String,
            'section': pl.String,
            'severity': pl.String,
            'status': pl.String,
            'count': pl.UInt32,
        },
    )


def build_project_summary(
    align_flags_df: pl.DataFrame | None,
    var_flags_df: pl.DataFrame | None,
    merged_flags_df: pl.DataFrame,
) -> pl.DataFrame:
    """Build the project QC summary table with alignment_qc, variants_qc, and total rows."""
    rows = []
    if align_flags_df is not None:
        rows.append(summarize_status_row('alignment_qc', align_flags_df['QC_status']))
    if var_flags_df is not None:
        rows.append(summarize_status_row('variants_qc', var_flags_df['QC_status']))
    rows.append(summarize_status_row('total', merged_flags_df['QC_status']))

    return pl.DataFrame(
        rows,
        schema={
            'section': pl.String,
            'N_samples': pl.UInt32,
            'N_PASS': pl.UInt32,
            'N_WARN': pl.UInt32,
            'N_FAIL': pl.UInt32,
            'failure_rate': pl.Float64,
        },
    )


def _find_dataset_and_view(config: dict, preferred_keys: tuple[str, ...]):
    """Locate a dataset and view entry in an input datavzrd config by key priority."""
    datasets = config.get('datasets') or {}
    views = config.get('views') or {}
    for key in preferred_keys:
        if key in datasets and key in views:
            return copy.deepcopy(datasets[key]), copy.deepcopy(views[key])
    raise ValueError(f'Could not find expected dataset/view among {preferred_keys} in datavzrd config')


def _qc_flags_barplot_spec(severities: list[str]) -> str:
    """Return a Vega-Lite v5 bar plot spec plotting FAIL and WARN flags separately."""
    palette = {
        'FAIL': ('FAIL flags', ['PASS', 'FAIL'], ['#00a000', '#ff0000']),
        'WARN': ('WARN flags', ['PASS', 'WARN'], ['#00a000', '#ffa500']),
    }
    panels = []
    for sev in ('FAIL', 'WARN'):
        if sev not in severities:
            continue
        title, domain, colors = palette[sev]
        panels.append({
            'title': title,
            'width': 550,
            'height': {'step': 24},
            'transform': [{'filter': f"datum.severity == '{sev}'"}],
            'mark': 'bar',
            'encoding': {
                'y': {
                    'field': 'flag',
                    'type': 'nominal',
                    'sort': None,
                    'title': 'QC flag',
                    'axis': {'labelLimit': 350},
                },
                'x': {
                    'field': 'count',
                    'type': 'quantitative',
                    'title': 'Number of samples',
                },
                'color': {
                    'field': 'status',
                    'type': 'nominal',
                    'title': 'Status',
                    'scale': {
                        'domain': domain,
                        'range': colors,
                    },
                },
                'tooltip': [
                    {'field': 'flag', 'type': 'nominal', 'title': 'Flag'},
                    {'field': 'section', 'type': 'nominal', 'title': 'Section'},
                    {'field': 'severity', 'type': 'nominal', 'title': 'Severity'},
                    {'field': 'status', 'type': 'nominal', 'title': 'Status'},
                    {'field': 'count', 'type': 'quantitative', 'title': 'Samples'},
                ],
            },
        })

    spec = {
        '$schema': 'https://vega.github.io/schema/vega-lite/v5.json',
        'vconcat': panels,
        'resolve': {'scale': {'color': 'independent'}},
    }
    return json.dumps(spec, indent=2)


