def build_unified_datavzrd_config(
    project_name: str,
    summary_tsv_path: str,
    summary_script_path: str,
    merged_flags_tsv_path: str,
    merged_flags_df: pl.DataFrame,
    active_flag_cols: list[str],
    flags_summary_tsv_path: str | None = None,
    flag_summary_severities: list[str] | None = None,
    max_rows_per_page: int = DEFAULT_MAX_ROWS_PER_PAGE,
    align_config: dict | None = None,
    var_config: dict | None = None,
    align_metrics_tsv: str | None = None,
    var_metrics_tsv: str | None = None,
    align_criteria_tsv: str | None = None,
    var_criteria_tsv: str | None = None,
) -> dict:
    """Merge align and var datavzrd configs with project summary, combined flags, bar plot, and links.

    View names use numeric prefixes (01_, 02_, ...) because datavzrd sorts
    non-default views alphabetically in its dropdown menu.
    """
    datasets = {}
    views = {}

    summary_view = '01_project_qc_summary'
    flags_view = '02_qc_flags'
    flags_summary_view = '03_qc_flags_summary'
    align_metrics_view_name = '04_align_qc_metrics'
    var_metrics_view_name = '05_var_qc_metrics'
    align_criteria_view_name = '06_align_qc_criteria'
    var_criteria_view_name = '07_var_qc_criteria'

    # 1. Project QC summary (default view, rendered with clean large-font HTML layout)
    datasets[summary_view] = {
        'path': summary_tsv_path,
        'separator': '\t',
    }
    views[summary_view] = {
        'dataset': summary_view,
        'desc': 'Project QC summary (PASS / WARN / FAIL counts and failure rate)',
        'render-html': {
            'script-path': summary_script_path,
        },
    }

    # 2. Merged QC flags table
    qc_flags_columns = {
        'sample_id': {'label': 'Sample ID', 'display-mode': 'pinned'},
    }
    if 'bam_sample_id' in merged_flags_df.columns:
        qc_flags_columns['bam_sample_id'] = {'label': 'BAM Sample ID', 'display-mode': 'pinned'}
    if 'vcf_sample_id' in merged_flags_df.columns:
        qc_flags_columns['vcf_sample_id'] = {'label': 'VCF Sample ID', 'display-mode': 'pinned'}
    qc_flags_columns['N_warning_flags'] = {'label': 'N warning flags', 'display-mode': 'pinned'}
    qc_flags_columns['N_fail_flags'] = {'label': 'N fail flags', 'display-mode': 'pinned'}
    qc_flags_columns['QC_status'] = {
        'label': 'QC status',
        'display-mode': 'pinned',
        'plot': {
            'heatmap': {
                'scale': 'ordinal',
                'domain': ['PASS', 'WARN', 'FAIL'],
                'range': ['#00a000', '#ffa500', '#ff0000'],
            }
        },
    }
    for col in active_flag_cols:
        is_warn = '-WARN-' in col
        raised_label = 'WARN' if is_warn else 'FAIL'
        raised_color = '#ffa500' if is_warn else '#ff0000'
        qc_flags_columns[col] = {
            'plot': {
                'heatmap': {
                    'scale': 'ordinal',
                    'domain': ['PASS', raised_label],
                    'range': ['#ffffff', raised_color],
                }
            }
        }

    datasets[flags_view] = {
        'path': merged_flags_tsv_path,
        'separator': '\t',
    }
    views[flags_view] = {
        'dataset': flags_view,
        'desc': 'Combined QC flags status (flags raised in >= 1 sample)',
        'render-table': {'columns': qc_flags_columns},
    }

    # 3. QC flags PASS / FAIL and PASS / WARN summary bar plots
    if flags_summary_tsv_path and flag_summary_severities:
        datasets[flags_summary_view] = {
            'path': flags_summary_tsv_path,
            'separator': '\t',
        }
        views[flags_summary_view] = {
            'dataset': flags_summary_view,
            'desc': 'Number of PASS / FAIL and PASS / WARN samples for each configured QC flag',
            'render-plot': {
                'spec': _qc_flags_barplot_spec(flag_summary_severities),
            },
        }

    sample_linked_views = [flags_view]

    # 4. Alignment QC metrics
    if align_config is not None:
        align_metrics_ds, align_metrics_view = _find_dataset_and_view(
            align_config, ('align_qc_metrics', 'qc_metrics')
        )
        if align_metrics_tsv:
            align_metrics_ds['path'] = align_metrics_tsv
        align_metrics_view['dataset'] = align_metrics_view_name
        align_metrics_view['desc'] = align_metrics_view.get('desc') or 'Alignment QC metrics'
        datasets[align_metrics_view_name] = align_metrics_ds
        views[align_metrics_view_name] = align_metrics_view
        sample_linked_views.append(align_metrics_view_name)

    # 5. Variant QC metrics
    if var_config is not None:
        var_metrics_ds, var_metrics_view = _find_dataset_and_view(
            var_config, ('var_qc_metrics', 'qc_metrics')
        )
        if var_metrics_tsv:
            var_metrics_ds['path'] = var_metrics_tsv
        var_metrics_view['dataset'] = var_metrics_view_name
        var_metrics_view['desc'] = var_metrics_view.get('desc') or 'Variant QC metrics'
        datasets[var_metrics_view_name] = var_metrics_ds
        views[var_metrics_view_name] = var_metrics_view
        sample_linked_views.append(var_metrics_view_name)

    # 6. Alignment QC criteria
    if align_config is not None:
        align_criteria_ds, align_criteria_view = _find_dataset_and_view(
            align_config, ('align_qc_criteria', 'qc_criteria')
        )
        if align_criteria_tsv:
            align_criteria_ds['path'] = align_criteria_tsv
        align_criteria_view['dataset'] = align_criteria_view_name
        align_criteria_view['desc'] = 'Alignment QC flags description'
        datasets[align_criteria_view_name] = align_criteria_ds
        views[align_criteria_view_name] = align_criteria_view

    # 7. Variant QC criteria
    if var_config is not None:
        var_criteria_ds, var_criteria_view = _find_dataset_and_view(
            var_config, ('var_qc_criteria', 'qc_criteria')
        )
        if var_criteria_tsv:
            var_criteria_ds['path'] = var_criteria_tsv
        var_criteria_view['dataset'] = var_criteria_view_name
        var_criteria_view['desc'] = 'Variant QC flags description'
        datasets[var_criteria_view_name] = var_criteria_ds
        views[var_criteria_view_name] = var_criteria_view

    # Link all sample-level tables to each other by sample_id
    for src_view in sample_linked_views:
        links = {}
        for dst_view in sample_linked_views:
            if dst_view == src_view:
                continue
            links[dst_view] = {
                'column': 'sample_id',
                'table-row': f'{dst_view}/sample_id',
                'optional': True,
            }
        if links:
            datasets[src_view]['links'] = links

    return {
        'name': project_name,
        'default-view': summary_view,
        'max-in-memory-rows': max_rows_per_page,
        'datasets': datasets,
        'views': views,
    }


def parse_arguments(argv=None):
    version_parser = argparse.ArgumentParser(add_help=False)
    version_parser.add_argument('--version', action='version', version=f'{VERSION}')
    version_parser.parse_known_args(argv)

    parser = argparse.ArgumentParser(description='Create unified project QC summary and datavzrd report config')
    parser.add_argument('--project_id', default=None, help='Project identifier used as report title')
    parser.add_argument(
        '--max_rows_per_page',
        '--max_in_memory_rows',
        dest='max_rows_per_page',
        type=int,
        default=DEFAULT_MAX_ROWS_PER_PAGE,
        help=f'Maximum number of rows per datavzrd page (max-in-memory-rows; default: {DEFAULT_MAX_ROWS_PER_PAGE})',
    )
    parser.add_argument('--align_datavzrd_yml', default=None, help='Datavzrd YAML config from summarise_align_qc.py')
    parser.add_argument('--align_metrics_tsv', default=None, help='Alignment QC metrics TSV from summarise_align_qc.py')
    parser.add_argument('--align_qc_flags_tsv', default=None, help='Alignment QC flags TSV from summarise_align_qc.py')
    parser.add_argument('--align_qc_criteria_tsv', default=None, help='Optional alignment QC criteria TSV (overrides YAML path)')
    parser.add_argument('--var_datavzrd_yml', default=None, help='Datavzrd YAML config from summarise_var_qc.py')
    parser.add_argument('--var_metrics_tsv', default=None, help='Variant QC metrics TSV from summarise_var_qc.py')
    parser.add_argument('--var_qc_flags_tsv', default=None, help='Variant QC flags TSV from summarise_var_qc.py')
    parser.add_argument('--var_qc_criteria_tsv', default=None, help='Optional variant QC criteria TSV (overrides YAML path)')
    parser.add_argument('--output_prefix', required=True, help='Prefix for output files (summary TSV, flags TSV, datavzrd YAML)')

    args = parser.parse_args(argv)

    if args.max_rows_per_page < 1:
        parser.error('--max_rows_per_page must be at least 1')

    has_align = any((args.align_datavzrd_yml, args.align_metrics_tsv, args.align_qc_flags_tsv, args.align_qc_criteria_tsv))
    has_var = any((args.var_datavzrd_yml, args.var_metrics_tsv, args.var_qc_flags_tsv, args.var_qc_criteria_tsv))
    if not has_align and not has_var:
        parser.error('Provide alignment QC inputs, variant QC inputs, or both')
    if has_align and (not args.align_datavzrd_yml or not args.align_qc_flags_tsv):
        parser.error('Alignment QC requires both --align_datavzrd_yml and --align_qc_flags_tsv')
    if has_var and (not args.var_datavzrd_yml or not args.var_qc_flags_tsv):
        parser.error('Variant QC requires both --var_datavzrd_yml and --var_qc_flags_tsv')

    return args


def main(argv=None):
    args = parse_arguments(argv)

    align_flags_df = None
    align_config = None
    if args.align_qc_flags_tsv:
        log(f'Reading alignment QC flags from {args.align_qc_flags_tsv}')
        align_flags_df = read_flags_table(args.align_qc_flags_tsv, ['sample_id', 'bam_sample_id'])
        with open(args.align_datavzrd_yml, 'r') as handle:
            align_config = yaml.safe_load(handle) or {}

    var_flags_df = None
    var_config = None
    if args.var_qc_flags_tsv:
        log(f'Reading variant QC flags from {args.var_qc_flags_tsv}')
        var_flags_df = read_flags_table(args.var_qc_flags_tsv, ['sample_id', 'vcf_sample_id'])
        with open(args.var_datavzrd_yml, 'r') as handle:
            var_config = yaml.safe_load(handle) or {}

    merged_flags_df, active_flag_cols = merge_qc_flags(align_flags_df, var_flags_df)
    summary_df = build_project_summary(align_flags_df, var_flags_df, merged_flags_df)
    flags_summary_df = build_qc_flags_summary(align_flags_df, var_flags_df)

    summary_path = f'{args.output_prefix}.project_qc_summary.tsv'
    summary_df.write_csv(summary_path, separator='\t', null_value='NA')
    log(f'Project QC summary saved to {summary_path}')

    flags_path = f'{args.output_prefix}.qc_flags.tsv'
    merged_flags_df.write_csv(flags_path, separator='\t', null_value='NA')
    log(f'Merged QC flags saved to {flags_path} ({len(active_flag_cols)} active flag columns)')

    flags_summary_path = f'{args.output_prefix}.qc_flags_summary.tsv'
    flags_summary_df.write_csv(flags_summary_path, separator='\t', null_value='NA')
    log(f'QC flags summary saved to {flags_summary_path} ({flags_summary_df.height // 2} configured flags)')

    summary_script_path = f'{args.output_prefix}.project_qc_summary.js'
    with open(summary_script_path, 'w') as handle:
        handle.write(_project_summary_html_script())
    log(f'Project QC summary HTML script saved to {summary_script_path}')

    flag_summary_severities = flags_summary_df['severity'].unique().to_list() if flags_summary_df.height > 0 else []

    project_name = f'{args.project_id} QC report' if args.project_id else 'QC metrics report'
    datavzrd_config = build_unified_datavzrd_config(
        project_name=project_name,
        summary_tsv_path=summary_path,
        summary_script_path=summary_script_path,
        merged_flags_tsv_path=flags_path,
        merged_flags_df=merged_flags_df,
        active_flag_cols=active_flag_cols,
        flags_summary_tsv_path=flags_summary_path,
        flag_summary_severities=flag_summary_severities,
        max_rows_per_page=args.max_rows_per_page,
        align_config=align_config,
        var_config=var_config,
        align_metrics_tsv=args.align_metrics_tsv,
        var_metrics_tsv=args.var_metrics_tsv,
        align_criteria_tsv=args.align_qc_criteria_tsv,
        var_criteria_tsv=args.var_qc_criteria_tsv,
    )

    datavzrd_path = f'{args.output_prefix}.datavzrd.yml'
    with open(datavzrd_path, 'w') as handle:
        yaml.safe_dump(datavzrd_config, handle, sort_keys=False)
    log(f'Unified datavzrd config saved to {datavzrd_path}')


if __name__ == '__main__':
    main()
